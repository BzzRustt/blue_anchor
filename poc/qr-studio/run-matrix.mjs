// Headless matrix: synthetic images x URLs x versions x renderers -> RESULTS.md
// Run: node poc/qr-studio/run-matrix.mjs
import { writeFileSync } from 'node:fs';
import { renderQr, validate } from './core.mjs';
import { QRCode, decoders, jpeg, syntheticImages } from './node-env.mjs';

const base = 'https://scanme.example/t/';
const URLS = {
  short: (base + 'k7Qp2xZ').padEnd(30, '0').slice(0, 30),
  medium: base + 'k7Qp2xZ?utm_source=poster&utm_medium=print&utm_campaign=autumn-launch&ref=abc'.padEnd(80 - base.length, 'x'),
  long: base + 'k7Qp2xZ?' + 'utm_campaign=autumn-launch-event-series&ref=abcdefghij&'.repeat(4).padEnd(200 - base.length - 8, 'z'),
};
for (const [k, v] of Object.entries(URLS)) URLS[k] = v.slice(0, { short: 30, medium: 80, long: 200 }[k]);
const VERSIONS = ['minimal', 7, 10];
const RENDERERS = [['classic', {}], ['fs', {}], ['bayer', {}], ['fs+cross', { renderer: 'fs', cross: true }]];
const images = syntheticImages();
const SCALE = 4; // px per sub-cell -> 12 px per module

const rows = [];
for (const [imgName, im] of Object.entries(images))
  for (const [urlName, url] of Object.entries(URLS))
    for (const ver of VERSIONS)
      for (const [rName, ro] of RENDERERS) {
        if (rName === 'classic' && imgName !== Object.keys(images)[0]) continue; // classic ignores the image
        const opts = { ...im, lw: im.w, lh: im.h, renderer: rName, scale: SCALE, ...ro, version: ver === 'minimal' ? undefined : ver };
        const row = { img: rName === 'classic' ? '(none)' : imgName, urlName, len: url.length, ver, r: rName };
        let out;
        const t0 = performance.now();
        try { out = renderQr(QRCode, url, opts); } catch (e) { rows.push({ ...row, na: 'URL does not fit this version at ECC M' }); continue; }
        row.ms = performance.now() - t0;
        row.usedVer = out.matrix.version; row.modules = out.matrix.size;
        const v = await validate(out, url, decoders, jpeg);
        row.passed = v.passed; row.total = v.total;
        row.per = Object.fromEntries(Object.keys(decoders).map((d) => [d, v.results.filter((x) => x.per[d]).length]));
        row.fails = v.results.filter((x) => !x.pass).map((x) => x.name);
        rows.push(row);
        process.stdout.write('.');
      }
console.log();

const ok = rows.filter((r) => !r.na);
const pct = (a, b) => (b ? ((100 * a) / b).toFixed(0) + '%' : '-');
const agg = (key) => {
  const g = {};
  for (const r of ok) { const k = r[key]; g[k] ??= { n: 0, p: 0, t: 0, ms: 0, full: 0, nat: 0 }; const a = g[k]; a.n++; a.p += r.passed; a.t += r.total; a.ms += r.ms; a.full += r.passed === r.total ? 1 : 0; }
  return Object.entries(g).map(([k, a]) => `| ${k} | ${a.n} | ${pct(a.p, a.t)} | ${a.full}/${a.n} | ${(a.ms / a.n).toFixed(1)} |`).join('\n');
};
const hdr = (c) => `| ${c} | runs | condition pass rate (both decoders) | runs passing ALL conditions | avg render ms |\n|---|---|---|---|---|`;
const per = { jsqr: [0, 0], zxing: [0, 0] };
for (const r of ok) for (const d of Object.keys(per)) { per[d][0] += r.per[d]; per[d][1] += r.total; }

const md = `# QR Studio PoC results (generated)

Generated by \`node poc/qr-studio/run-matrix.mjs\` on ${new Date().toISOString().slice(0, 10)}, Node ${process.version}.

**READ THIS FIRST.** The test images are SYNTHETIC shapes drawn by code (face-like blobs, a gradient, a ring-and-bar logo shape, noisy texture), not real photographs, and I could not download photos. The "conditions" are software simulations (box downscale, Gaussian blur, contrast reduction, small rotation, JPEG q60 via sharp). None of this proves that a printed or on-screen code scans on a real phone, and none of it shows a real face is recognisable. Rendered at ${SCALE} px per sub-cell (12 px per module); decoders: jsQR and zxing-wasm. A condition counts as passed only if BOTH decoders return text exactly equal to the input URL.

URL lengths: short ${URLS.short.length}, medium ${URLS.medium.length}, long ${URLS.long.length} chars. ECC level M. "minimal" = smallest version that fits. Rows where the URL does not fit a forced version are marked n/a.

Overall single-decoder condition pass rate: jsQR ${pct(...per.jsqr)}, zxing-wasm ${pct(...per.zxing)}.

## By renderer
${hdr('renderer')}
${agg('r')}

## By requested version
${hdr('version')}
${agg('ver')}

## By synthetic image
${hdr('image')}
${agg('img')}

## By URL
${hdr('url')}
${agg('urlName')}

## Every run
| image | URL | len | version asked / used (modules) | renderer | render ms | passed | jsQR | zxing | failed conditions |
|---|---|---|---|---|---|---|---|---|---|
${rows.map((r) => r.na ? `| ${r.img} | ${r.urlName} | ${r.len} | ${r.ver} | ${r.r} | - | n/a | - | - | ${r.na} |`
  : `| ${r.img} | ${r.urlName} | ${r.len} | ${r.ver} / v${r.usedVer} (${r.modules}) | ${r.r} | ${r.ms.toFixed(1)} | ${r.passed}/${r.total} | ${r.per.jsqr} | ${r.per.zxing} | ${r.fails.join(', ') || '-'} |`).join('\n')}

## Not proven (TODO for you, the physical test)
- Print the 20-code sheet from plan section 7 (paper at 3 sizes, a sticker, a card, a T-shirt transfer) and scan on 2 iPhones and 2 Android phones (one older) with native camera, Google Lens and one third-party app, from screen and paper. Record failures.
- Judge recognisability of real portraits, logos and artwork with real people (5-person panel). Synthetic blobs say nothing about this.
- Render time here is Node on this PC, not a mid-range phone.
`;
writeFileSync(new URL('./RESULTS.md', import.meta.url), md);
console.log(`wrote RESULTS.md: ${ok.length} runs, ${rows.length - ok.length} n/a`);
